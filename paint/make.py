#!/usr/bin/env python3
"""Bakes the brush paintings into CSS, so no page has to paint anything in the browser.

Runs brush.js once in headless Chromium and writes:
  ../paint.css              --paint-zero (the 0 of the logo), --paint-btn (the sign-up button)
  ../overtones/paint.css  --paint-tile (the f0 tile), --paint-0 .. --paint-6 (one per badge colour)
The paintings are random, so each run gives slightly different strokes. Run it only when the look changes.
"""
import json, os, re, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)

PAGE = r'''<!doctype html><meta charset="utf-8"><script src="file://%s/brush.js"></script><script>
addEventListener('load', () => {
  const N = 21, TAU = Math.PI * 2, flow = (u, v) => -0.45 + 0.8 * Math.sin(u * 4.2 + v * 2.6);
  const small = (sheet, w, q) => { const c = document.createElement('canvas'); c.width = w; c.height = Math.round(w * sheet.height / sheet.width);
    const g = c.getContext('2d'); g.imageSmoothingQuality = 'high'; g.drawImage(sheet, 0, 0, c.width, c.height); return c.toDataURL('image/webp', q); };
  const out = {};
  // the 0: tiny dabs, the rainbow once round the ring (the sheet is stretched over the 0, which is narrower than tall, hence 0.73)
  out.zero = small(f0Sheet({ hw: 13, len: [1.3, 2], jit: 3, hj: 3.2, soft: 0.6, dry: 0, hue: (u, v) => Math.atan2(v - 0.5, (u - 0.5) * 0.73) / TAU * N + 16, dir: flow }), 300, 0.9);
  // the sign-up button and the f0 tile: the same tiny dabs, the rainbow round the middle
  const btn = f0Sheet({ hw: 6, len: [1.3, 2], jit: 3, hj: 3.2, soft: 0.6, dry: 0, hue: (u, v) => Math.atan2(v - 0.5, (u - 0.5) * 1.3) / TAU * N + 16, dir: flow });
  out.btn = small(btn, 560, 0.8); out.tile = small(btn, 160, 0.9);
  // badges: one sheet per logo colour, quiet strokes in the neighbouring hues
  for (let h = 0; h < 7; h++) out['b' + h] = small(f0Sheet({ hw: 40, len: [2.4, 4], jit: 0.6, hj: 1.4, soft: 0.32, dry: 0, hue: () => h * 3, dir: (u, v) => -0.35 + 0.6 * Math.sin(u * 4.2 + v * 2.6) }), 320, 0.84);
  const pre = document.createElement('pre'); pre.id = 'out'; pre.textContent = JSON.stringify(out); document.body.appendChild(pre);
});
</script>'''

def main():
    chromium = shutil.which('chromium') or shutil.which('chromium-browser') or shutil.which('google-chrome')
    if not chromium:
        sys.exit('needs chromium on the PATH')
    with tempfile.TemporaryDirectory() as tmp:
        page = os.path.join(tmp, 'paint.html')
        open(page, 'w').write(PAGE % SITE)
        dom = subprocess.run([chromium, '--headless=new', '--no-sandbox', '--disable-gpu', '--allow-file-access-from-files',
                              '--virtual-time-budget=60000', '--dump-dom', 'file://' + page], capture_output=True, text=True, timeout=300).stdout
    m = re.search(r'<pre id="out">(.*?)</pre>', dom, re.S)
    if not m:
        sys.exit('painting failed: no output from the page')
    o = json.loads(m.group(1).replace('&amp;', '&'))
    head = '/* Generated by paint/make.py from brush.js. Do not edit. */\n'
    site = head + ':root {\n  --paint-zero: url("%s");\n  --paint-btn: url("%s");\n}\n' % (o['zero'], o['btn'])
    ot = head + ':root {\n  --paint-tile: url("%s");\n' % o['tile'] + ''.join('  --paint-%d: url("%s");\n' % (h, o['b%d' % h]) for h in range(7)) + '}\n'
    open(os.path.join(SITE, 'paint.css'), 'w').write(site)
    open(os.path.join(SITE, 'overtones', 'paint.css'), 'w').write(ot)
    print('paint.css %d KB, overtones/paint.css %d KB' % (len(site) // 1024, len(ot) // 1024))

if __name__ == '__main__':
    main()
